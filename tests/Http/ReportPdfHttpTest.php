<?php

declare(strict_types=1);

namespace SeoControlCenter\Tests\Http;

use PHPUnit\Framework\TestCase;
use SeoControlCenter\Core\Support\Clock;
use SeoControlCenter\Core\Support\FrozenClock;
use SeoControlCenter\Domain\SearchConsole\DailyMetrics;
use SeoControlCenter\Domain\SearchConsole\DimensionRow;
use SeoControlCenter\Domain\SearchConsole\Metrics;
use SeoControlCenter\Modules\Reports\ReportCustomization;
use SeoControlCenter\Modules\Reports\ReportService;
use SeoControlCenter\Tests\Support\Fakes\FakeMailer;
use SeoControlCenter\Tests\Support\Fakes\InMemorySearchPerformance;
use SeoControlCenter\Tests\Support\PdfText;
use SeoControlCenter\Tests\Support\Scenario;

/**
 * Report PDFs (ADR-033): the download from the report page and the copy
 * attached to report e-mails, with the same content, sections and branding.
 */
final class ReportPdfHttpTest extends TestCase
{
    private Scenario $s;
    private FakeMailer $mailer;

    protected function setUp(): void
    {
        $this->s = new Scenario();
        $this->s->container->instance(Clock::class, new FrozenClock(new \DateTimeImmutable('2026-10-02 12:00:00 UTC')));
        $this->mailer = $this->s->container->get(FakeMailer::class);
        $performance = $this->s->container->get(InMemorySearchPerformance::class);
        $project = $this->s->acmeProject->id;
        $performance->upsertDailyTotals($project, [
            new DailyMetrics('2026-09-16', new Metrics(40, 1000, 9.0)),
            new DailyMetrics('2026-09-24', new Metrics(50, 1200, 8.0)),
        ]);
        $performance->replaceDay($project, '2026-09-24', [
            'query' => [new DimensionRow('čevapi near Hodžić street', new Metrics(20, 300, 3.0))],
            'page' => [new DimensionRow('https://shop.acme.test/shoes/' . str_repeat('very-long-segment-', 12), new Metrics(30, 500, 4.0))],
        ]);
    }

    private function url(string $path = ''): string
    {
        return '/projects/' . $this->s->acmeProject->publicId . '/reports' . $path;
    }

    public function testViewersDownloadThePdfOfThePeriod(): void
    {
        $viewer = $this->s->loggedIn($this->s->viewer);
        $page = (string) $viewer->get($this->url('/view?frequency=weekly'))->getBody();
        self::assertStringContainsString('href="' . $this->url('/pdf?frequency=weekly&amp;to=2026-09-27') . '"', $page);

        $response = $viewer->get($this->url('/pdf?frequency=weekly&to=2026-09-27'));
        self::assertSame(200, $response->getStatusCode());
        self::assertSame('application/pdf', $response->getHeaderLine('Content-Type'));
        self::assertSame('attachment; filename="seo-report-acme-shop-2026-09-27.pdf"', $response->getHeaderLine('Content-Disposition'));
        self::assertSame('no-store', $response->getHeaderLine('Cache-Control'));
        $pdf = (string) $response->getBody();
        self::assertStringStartsWith('%PDF-1.7', $pdf);
        self::assertStringEndsWith("%%EOF\n", $pdf);
        self::assertLessThan(150_000, strlen($pdf), 'Fonts are subset.');

        $read = new PdfText($pdf);
        $text = $read->text();
        foreach ([
            'SEO Control Center', 'Acme Shop: Week 39 · 21–27 September 2026', 'compared with 2026-09-14 – 2026-09-20',
            'Search traffic', 'Clicks', '50', '↑ +25.0 % vs previous 7 days', '↑ +20.0 % vs previous 7 days', 'Clicks per day', '2026-09-21', '2026-09-27',
            'Top queries', 'čevapi near Hodžić street', 'Top pages', 'Keyword rankings', 'No rank check in this period.', 'Opportunities',
            'Generated by SEO Control Center from the data imported on this server.',
        ] as $expected) {
            self::assertStringContainsString($expected, $text);
        }
        self::assertMatchesRegularExpression('#/shoes/very-long-segment-.*…#u', $text, 'Long URLs are shortened to the column.');
        self::assertMatchesRegularExpression('/Page 1 of [1-9]/', $text);
        self::assertSame(['http://scc.test/projects/' . $this->s->acmeProject->publicId . '/reports/view?frequency=weekly&to=2026-09-27'], $read->links());
        self::assertSame(2, count($read->fontNames()));
        self::assertStringNotContainsString('?', str_replace('?frequency', '', $text), 'Every character has a glyph.');

        $future = new PdfText((string) $viewer->get($this->url('/pdf?frequency=weekly&to=2026-10-11'))->getBody());
        self::assertStringContainsString('Week 39', $future->text(), 'Periods that have not ended fall back to the latest complete one.');
        $monthly = new PdfText((string) $viewer->get($this->url('/pdf?frequency=monthly'))->getBody());
        self::assertStringContainsString('September 2026', $monthly->text());
    }

    public function testRankingsAuditAndOpportunitiesAppearWithTheirFigures(): void
    {
        $id = $this->s->acmeProject->id;
        $rankings = $this->s->container->get(\SeoControlCenter\Tests\Support\Fakes\InMemoryRankings::class);
        $device = $rankings->settings($id)->device->value;
        $rankings->days[$id . ':' . $device . ':2026-09-20'] = new \SeoControlCenter\Domain\Rankings\RankingDay('2026-09-20', 40, 30, 4, 12, 18.2, 22.5);
        $rankings->days[$id . ':' . $device . ':2026-09-27'] = new \SeoControlCenter\Domain\Rankings\RankingDay('2026-09-27', 40, 32, 6, 11, 16.0, 25.0);
        $audits = $this->s->container->get(\SeoControlCenter\Tests\Support\Fakes\InMemorySiteAudit::class);
        $audit = $audits->create($id, $this->s->acme->id, 'https://shop.acme.test/', 100, 'manual', null);
        $audits->finish($audit->id, 'completed', 87, ['error' => 3, 'warning' => 5, 'notice' => 0], [
            ['type' => \SeoControlCenter\Modules\SiteAudit\IssueType::MissingTitle, 'pageId' => 1],
            ['type' => \SeoControlCenter\Modules\SiteAudit\IssueType::MissingTitle, 'pageId' => 2],
        ], null);
        $this->s->container->get(\SeoControlCenter\Tests\Support\Fakes\InMemoryOpportunities::class)->sync($id, [
            new \SeoControlCenter\Domain\Opportunities\Opportunity(\SeoControlCenter\Domain\Opportunities\OpportunityType::InternalLinks, 'page:https://shop.acme.test/a', 'Link to the Hodžić guide', 'Few internal links point here.', [], 60, 70, 1, 40),
        ]);

        $text = (new PdfText((string) $this->s->loggedIn($this->s->viewer)->get($this->url('/pdf'))->getBody()))->text();
        foreach ([
            '40 keywords · ' . $device . ' · check of 2026-09-27 vs 2026-09-20', 'Visibility', '25.0 %', '↑ +2.5 pts vs 2026-09-20', '↑ +2 vs 2026-09-20', '↓ -1 vs 2026-09-20', '16.0',
            'Site audit', 'Health score', '87 / 100', 'Errors', 'Warnings', 'Most frequent issues',
            'Opportunities', '1 open, highest priority first', '1. Link to the Hodžić guide',
        ] as $expected) {
            self::assertStringContainsString($expected, $text);
        }
    }

    public function testSectionsBrandingAndLogoApplyToThePdf(): void
    {
        $owner = $this->s->loggedIn($this->s->owner);
        $owner->get($this->url());
        self::assertSame(303, $owner->post($this->url('/branding'), ['product_name' => 'Acme Client SEO', 'accent_color' => '#1255aa', 'report_footer' => 'Prepared for the Acme client'])->getStatusCode());
        self::assertSame(303, $owner->post($this->url('/sections'), ['sections' => ['rankings']])->getStatusCode());
        $chunk = static fn(string $type, string $data): string => pack('N', strlen($data)) . $type . $data . pack('N', crc32($type . $data));
        $png = "\x89PNG\r\n\x1a\n" . $chunk('IHDR', pack('NNCCCCC', 32, 16, 8, 2, 0, 0, 0)) . $chunk('IDAT', (string) gzcompress(str_repeat("\0" . str_repeat("\x20\x55\xaa", 32), 16))) . $chunk('IEND', '');
        $this->s->container->get(ReportCustomization::class)->saveLogo($this->s->owner, $this->s->acmeProject, $png, new \SeoControlCenter\Core\Support\ClientInfo('127.0.0.1', 'test', null));

        $read = new PdfText((string) $owner->get($this->url('/pdf'))->getBody());
        $text = $read->text();
        self::assertStringContainsString('Acme Client SEO', $text);
        self::assertStringContainsString('Prepared for the Acme client', $text);
        self::assertStringContainsString('Keyword rankings', $text);
        self::assertStringNotContainsString('Search traffic', $text);
        self::assertStringNotContainsString('Opportunities', $text);
        self::assertStringNotContainsString('SEO Control Center', $text);
        self::assertStringContainsString('0.071 0.333 0.667 rg', (string) gzuncompress((string) self::firstContentStream($read->pdf)), 'The accent colour is used.');
        self::assertSame(1, $read->imageCount(), 'The workspace logo is embedded.');
    }

    public function testReportEmailsCarryThePdf(): void
    {
        $this->mailer->configured = true;
        $this->s->container->get(ReportService::class)->send($this->s->acme->id, $this->s->acmeProject->publicId, 'weekly', '2026-09-27', ['client@shop.test'], 'test');

        $message = $this->mailer->sent[0];
        self::assertCount(1, $message->attachments);
        $attachment = $message->attachments[0];
        self::assertSame(['seo-report-acme-shop-2026-09-27.pdf', 'application/pdf'], [$attachment->fileName, $attachment->contentType]);
        self::assertStringContainsString('↑ +25.0 % vs previous 7 days', (new PdfText($attachment->content))->text());
        self::assertNotNull($message->html, 'The HTML and text versions stay.');
    }

    public function testOtherWorkspacesGetNotFound(): void
    {
        $rival = $this->s->loggedIn($this->s->rivalOwner);
        self::assertSame(404, $rival->get($this->url('/pdf'))->getStatusCode());
        self::assertSame(303, $this->s->browser()->get($this->url('/pdf'))->getStatusCode(), 'Guests are sent to sign in.');
    }

    private static function firstContentStream(string $pdf): ?string
    {
        if (preg_match('/\/Contents (\d+) 0 R/', $pdf, $m) !== 1) {
            return null;
        }
        preg_match('/\n' . $m[1] . " 0 obj\n<<[^>]*>>\nstream\n(.*?)\nendstream/s", $pdf, $s);

        return $s[1] ?? null;
    }
}
