<?php

declare(strict_types=1);

namespace SeoControlCenter\Modules\Reports;

use SeoControlCenter\Core\Branding\Branding;
use SeoControlCenter\Core\Pdf\PdfDocument;
use SeoControlCenter\Core\Pdf\TrueTypeFont;
use SeoControlCenter\Domain\SearchConsole\DimensionRow;
use SeoControlCenter\Domain\SearchConsole\Metrics;

/**
 * The project report as a PDF (A4), with the same content and section
 * choices as the printable report page: search KPIs with a daily clicks
 * chart, top pages and queries, rankings, GA4, site and browser audit, and
 * open opportunities. Built in-house (PdfDocument) with the bundled IBM Plex
 * Sans fonts; one report per instance.
 */
final class ReportPdf
{
    private const float MARGIN = 40.0;
    private const float CONTENT = PdfDocument::WIDTH - 2 * self::MARGIN;
    private const float BOTTOM = PdfDocument::HEIGHT - 56.0;
    private const string TEXT = '#1f2937';
    private const string MUTED = '#6b7280';
    private const string BORDER = '#e5e7eb';
    private const string SHADE = '#f3f4f6';
    private const string GOOD = '#15803d';
    private const string BAD = '#b91c1c';
    private const string DEFAULT_ACCENT = '#2f5fd0';

    private PdfDocument $pdf;
    private int $page = 0;
    private float $y = 0.0;
    private string $accent;

    private function __construct(private readonly string $fontDirectory) {}

    /**
     * @param array<string, mixed> $report from ReportBuilder::build()
     * @param ?string $logo image bytes (JPEG or PNG); unsupported images are left out
     */
    public static function render(string $fontDirectory, array $report, Branding $branding, ReportSections $sections, string $reportUrl, ?string $logo, \DateTimeImmutable $now): string
    {
        return (new self($fontDirectory))->build($report, $branding, $sections, $reportUrl, $logo, $now);
    }

    /** @param array<string, mixed> $report */
    public static function fileName(array $report): string
    {
        $slug = trim((string) preg_replace('/[^a-z0-9]+/', '-', strtolower($report['project']->name)), '-');

        return 'seo-report-' . ($slug !== '' ? substr($slug, 0, 40) : 'project') . '-' . $report['period']->toString() . '.pdf';
    }

    /** @param array<string, mixed> $report */
    private function build(array $report, Branding $branding, ReportSections $sections, string $reportUrl, ?string $logo, \DateTimeImmutable $now): string
    {
        $project = $report['project'];
        $this->accent = $branding->accentColor ?? self::DEFAULT_ACCENT;
        $this->pdf = new PdfDocument(sprintf('SEO report %s: %s', $project->name, $report['label']), $branding->name(), $now);
        $this->pdf->addFont('regular', TrueTypeFont::fromFile($this->fontDirectory . '/IBMPlexSans-Regular.ttf'));
        $this->pdf->addFont('bold', TrueTypeFont::fromFile($this->fontDirectory . '/IBMPlexSans-SemiBold.ttf'));
        $this->newPage();

        $this->header($report, $branding, $logo);
        $search = $report['search'];
        if ($sections->has('search')) {
            $this->search($report, $search);
        }
        if ($sections->has('rankings')) {
            $this->rankings($report['rankings']);
        }
        if ($sections->has('analytics') && ($report['analytics'] ?? null) !== null) {
            $this->analytics($report['analytics']);
        }
        if ($sections->has('audit')) {
            $this->audit($report['siteAudit'] ?? null, $report['renderedAudit'] ?? null);
        }
        if ($sections->has('opportunities')) {
            $this->opportunities($report);
        }

        $this->ensure(40);
        $this->y += 8;
        $this->paragraph('Online report with interactive charts:', 'regular', 9, self::MUTED);
        $this->ensure(14);
        $line = $this->fit($reportUrl, 'regular', 9, self::CONTENT);
        $this->pdf->text($this->page, self::MARGIN, $this->y + 9, $line, 'regular', 9, $this->accent);
        $this->pdf->link($this->page, self::MARGIN, $this->y - 1, $this->pdf->width($line, 'regular', 9), 13, $reportUrl);
        $this->y += 16;
        $this->paragraph('Search Console and Bing report the last days of a period with a short delay.', 'regular', 8, self::MUTED);

        $footer = $branding->reportFooter ?? sprintf('Generated by %s from the data imported on this server.', $branding->name());
        $total = $this->pdf->pageCount();
        for ($p = 0; $p < $total; ++$p) {
            $y = PdfDocument::HEIGHT - 34;
            $this->pdf->line($p, self::MARGIN, $y - 12, PdfDocument::WIDTH - self::MARGIN, $y - 12, self::BORDER);
            $pageLabel = sprintf('Page %d of %d', $p + 1, $total);
            $labelWidth = $this->pdf->width($pageLabel, 'regular', 8);
            $this->pdf->text($p, self::MARGIN, $y, $this->fit($footer, 'regular', 8, self::CONTENT - $labelWidth - 16), 'regular', 8, self::MUTED);
            $this->pdf->text($p, PdfDocument::WIDTH - self::MARGIN - $labelWidth, $y, $pageLabel, 'regular', 8, self::MUTED);
        }

        return $this->pdf->output();
    }

    /** @param array<string, mixed> $report */
    private function header(array $report, Branding $branding, ?string $logo): void
    {
        $x = self::MARGIN;
        $image = $logo !== null ? $this->pdf->addImage($logo) : null;
        if ($image !== null) {
            $height = 24.0;
            $width = min(120.0, $height * $image['width'] / $image['height']);
            $height = $width * $image['height'] / $image['width'];
            $this->pdf->image($this->page, $image['index'], $x, $this->y + (24 - $height) / 2, $width, $height);
            $x += $width + 8;
        }
        $this->pdf->text($this->page, $x, $this->y + 16, $branding->name(), 'bold', 11, $this->accent);
        $this->y += 34;
        $this->pdf->rect($this->page, self::MARGIN, $this->y, self::CONTENT, 2, $this->accent);
        $this->y += 14;
        $project = $report['project'];
        $this->paragraph($project->name . ': ' . $report['label'], 'bold', 20, self::TEXT, 26);
        $both = $report['search'] !== null && $report['search']['google'] !== null && $report['search']['bing'] !== null;
        $this->paragraph(sprintf('%s · %s – %s, compared with %s – %s%s', $project->primaryDomain, $report['period']->fromString(), $report['period']->toString(), $report['previousPeriod']->fromString(), $report['previousPeriod']->toString(), $both ? ' · Google + Bing' : ''), 'regular', 9.5, self::MUTED);
        $this->y += 10;
    }

    /**
     * @param array<string, mixed> $report
     * @param array{google: ?Metrics, googlePrevious: ?Metrics, bing: ?Metrics, bingPrevious: ?Metrics, combined: Metrics, combinedPrevious: Metrics}|null $search
     */
    private function search(array $report, ?array $search): void
    {
        $this->heading('Search traffic');
        if ($search === null) {
            $this->paragraph('No Search Console or Bing data is linked to this project yet.', 'regular', 10, self::MUTED);
            $this->y += 6;

            return;
        }
        $c = $search['combined'];
        $p = $search['combinedPrevious'];
        $hasPrevious = $p->impressions > 0;
        $both = $search['google'] !== null && $search['bing'] !== null;
        $tiles = [
            ['Clicks', number_format($c->clicks), $hasPrevious ? self::percentChange($c->clicks, $p->clicks) : null, $both ? sprintf('Google %s · Bing %s', number_format($search['google']->clicks), number_format($search['bing']->clicks)) : null],
            ['Impressions', number_format($c->impressions), $hasPrevious ? self::percentChange($c->impressions, $p->impressions) : null, $both ? sprintf('Google %s · Bing %s', number_format($search['google']->impressions), number_format($search['bing']->impressions)) : null],
            ['Average CTR', number_format($c->ctr() * 100, 1) . ' %', $hasPrevious ? self::change(($c->ctr() - $p->ctr()) * 100, '%+.1f pts', false) : null, null],
        ];
        if ($search['google'] !== null) {
            $before = $search['googlePrevious'];
            $tiles[] = ['Average position', number_format($search['google']->position, 1), $before !== null && $before->impressions > 0 ? self::change($search['google']->position - $before->position, '%+.1f', true) : null, $both ? 'Google only' : null];
        }
        $this->tiles($tiles, sprintf('vs previous %d days', $report['period']->days()));
        $this->chart($both ? 'Clicks per day · Google + Bing' : 'Clicks per day', $report['clicks']);

        foreach ([['Top pages', 'Page', $report['pages'], true], ['Top queries', 'Query', $report['queries'], false]] as [$title, $column, $rows, $isUrl]) {
            if ($rows === []) {
                $this->subheading($title);
                $this->paragraph('No rows for this period.', 'regular', 9.5, self::MUTED);
                $this->y += 4;
                continue;
            }
            $this->table(
                $title,
                [[$column, 263, 'left'], ['Clicks', 63, 'right'], ['Impr.', 70, 'right'], ['CTR', 60, 'right'], ['Pos.', 59, 'right']],
                array_map(static fn(DimensionRow $row): array => [
                    $isUrl ? ((string) preg_replace('#^https?://[^/]+#', '', $row->key) ?: '/') : $row->key,
                    number_format($row->metrics->clicks),
                    number_format($row->metrics->impressions),
                    number_format($row->metrics->ctr() * 100, 1) . ' %',
                    $row->metrics->impressions > 0 ? number_format($row->metrics->position, 1) : '–',
                ], $rows),
            );
        }
    }

    /** @param array{day: \SeoControlCenter\Domain\Rankings\RankingDay, previous: ?\SeoControlCenter\Domain\Rankings\RankingDay, winners: list<\SeoControlCenter\Domain\Rankings\RankingMove>, losers: list<\SeoControlCenter\Domain\Rankings\RankingMove>, device: string}|null $rankings */
    private function rankings(?array $rankings): void
    {
        $this->heading('Keyword rankings');
        if ($rankings === null) {
            $this->paragraph('No rank check in this period.', 'regular', 10, self::MUTED);
            $this->y += 6;

            return;
        }
        $day = $rankings['day'];
        $before = $rankings['previous'];
        $this->paragraph(sprintf('%d keywords · %s · check of %s%s', $day->keywords, $rankings['device'], $day->date, $before !== null ? ' vs ' . $before->date : ''), 'regular', 9, self::MUTED);
        $this->y += 4;
        $this->tiles([
            ['Visibility', number_format($day->visibility, 1) . ' %', $before !== null ? self::change($day->visibility - $before->visibility, '%+.1f pts', false) : null, null],
            ['Top 3', (string) $day->top3, $before !== null ? self::change($day->top3 - $before->top3, '%+d', false) : null, null],
            ['Top 10', (string) $day->top10, $before !== null ? self::change($day->top10 - $before->top10, '%+d', false) : null, null],
            ['Average position', $day->averagePosition !== null ? number_format($day->averagePosition, 1) : '–', null, null],
        ], $before !== null ? 'vs ' . $before->date : '');
        foreach ([['Winners', $rankings['winners']], ['Losers', $rankings['losers']]] as [$title, $moves]) {
            if ($moves === []) {
                continue;
            }
            $this->table(
                $title,
                [['Keyword', 335, 'left'], ['Before', 60, 'right'], ['Now', 60, 'right'], ['Change', 60, 'right']],
                array_map(static fn($m): array => [$m->keyword, (string) ($m->from ?? '>100'), (string) ($m->to ?? '>100'), sprintf('%+d', $m->change())], $moves),
            );
        }
    }

    /** @param array{metadata: array{from: string, to: string, currency: string, timezone: string, limited: bool, thresholded: bool, fetched_at: string}, rows: list<array{url: string, sessions: int, conversions: float, revenue: float}>, partial: bool} $analytics */
    private function analytics(array $analytics): void
    {
        $meta = $analytics['metadata'];
        $this->heading('Organic-search conversions and revenue');
        $this->paragraph(sprintf('%s to %s in %s. Currency: %s. Last project import %s UTC.', $meta['from'], $meta['to'], $meta['timezone'], $meta['currency'], $meta['fetched_at']), 'regular', 9, self::MUTED);
        if ($analytics['partial'] || $meta['limited'] || $meta['thresholded']) {
            $this->paragraph('Figures may be incomplete: period coverage, row limits or Google privacy thresholds apply.', 'regular', 9, self::BAD);
        }
        $this->y += 4;
        if ($analytics['rows'] === []) {
            $this->paragraph('No organic-search landing pages for this period.', 'regular', 9.5, self::MUTED);

            return;
        }
        $this->table(
            null,
            [['Landing URL', 270, 'left'], ['Sessions', 70, 'right'], ['Conversions', 80, 'right'], ['Revenue', 95, 'right']],
            array_map(static fn(array $r): array => [(string) preg_replace('#^https?://[^/]+#', '', $r['url']) ?: '/', number_format($r['sessions']), number_format($r['conversions'], 2), number_format($r['revenue'], 2) . ' ' . $meta['currency']], $analytics['rows']),
        );
    }

    /**
     * @param array{date: string, score: ?int, pages: int, errors: int, warnings: int, previousScore: ?int, previousDate: ?string, issues: list<array{label: string, severity: string, pages: int}>}|null $audit
     * @param array{date: string, pages: int, issues: list<array{type: string, label: string, severity: string, advice: string, pages: int, examples: list<string>, effort: int}>}|null $rendered
     */
    private function audit(?array $audit, ?array $rendered): void
    {
        if ($audit === null && $rendered === null) {
            return;
        }
        $this->heading('Site audit');
        if ($audit !== null) {
            $this->paragraph(sprintf('%s pages · audit of %s%s', number_format($audit['pages']), $audit['date'], $audit['previousDate'] !== null ? ' vs ' . $audit['previousDate'] : ''), 'regular', 9, self::MUTED);
            $this->y += 4;
            $this->tiles([
                ['Health score', $audit['score'] !== null ? $audit['score'] . ' / 100' : '–', $audit['score'] !== null && $audit['previousScore'] !== null ? self::change($audit['score'] - $audit['previousScore'], '%+d', false) : null, null],
                ['Errors', number_format($audit['errors']), null, null],
                ['Warnings', number_format($audit['warnings']), null, null],
                ['Pages crawled', number_format($audit['pages']), null, null],
            ], $audit['previousDate'] !== null ? 'vs ' . $audit['previousDate'] : '');
            if ($audit['issues'] !== []) {
                $this->table(
                    null,
                    [['Most frequent issues', 395, 'left'], ['Severity', 60, 'left'], ['Pages', 60, 'right']],
                    array_map(static fn(array $i): array => [$i['label'], ucfirst($i['severity']), number_format($i['pages'])], $audit['issues']),
                );
            }
        }
        if ($rendered !== null) {
            $this->subheading('Browser audit');
            $this->paragraph(sprintf('%d saved pages · %s UTC. Browser findings are separate from Google field measurements.', $rendered['pages'], $rendered['date']), 'regular', 9, self::MUTED);
            $this->y += 2;
            foreach ($rendered['issues'] as $issue) {
                $this->bullet(sprintf('%s: %d page%s.', $issue['label'], $issue['pages'], $issue['pages'] === 1 ? '' : 's'), $issue['advice']);
            }
            $this->y += 6;
        }
    }

    /** @param array<string, mixed> $report */
    private function opportunities(array $report): void
    {
        $this->heading('Opportunities');
        $this->paragraph(sprintf('%d open, highest priority first', $report['openOpportunities']), 'regular', 9, self::MUTED);
        $this->y += 2;
        if ($report['opportunities'] === []) {
            $this->paragraph('No open opportunities.', 'regular', 10, self::MUTED);

            return;
        }
        foreach ($report['opportunities'] as $i => $opportunity) {
            $this->bullet(sprintf('%d. %s', $i + 1, $opportunity->title), $opportunity->type->label() . ' · ' . \SeoControlCenter\Domain\Opportunities\ScoreBreakdown::summary($opportunity), false);
        }
        $this->y += 6;
    }

    /**
     * KPI tiles in one row.
     *
     * @param list<array{0: string, 1: string, 2: array{0: string, 1: string}|null, 3: ?string}> $tiles label, value, [change text, colour], note
     */
    private function tiles(array $tiles, string $compared): void
    {
        $this->ensure(70);
        $gap = 8.0;
        $width = (self::CONTENT - $gap * (count($tiles) - 1)) / count($tiles);
        foreach ($tiles as $i => [$label, $value, $change, $note]) {
            $x = self::MARGIN + $i * ($width + $gap);
            $this->pdf->rect($this->page, $x, $this->y, $width, 62, self::SHADE);
            $this->pdf->rect($this->page, $x, $this->y, 2.5, 62, $this->accent);
            $this->pdf->text($this->page, $x + 10, $this->y + 14, $this->fit($label, 'regular', 8.5, $width - 14), 'regular', 8.5, self::MUTED);
            $this->pdf->text($this->page, $x + 10, $this->y + 34, $this->fit($value, 'bold', 16, $width - 14), 'bold', 16, self::TEXT);
            if ($change !== null) {
                $text = $change[0] . ($compared !== '' ? ' ' . $compared : '');
                $this->pdf->text($this->page, $x + 10, $this->y + 47, $this->fit($text, 'regular', 7.5, $width - 14), 'regular', 7.5, $change[1]);
            }
            if ($note !== null) {
                $this->pdf->text($this->page, $x + 10, $this->y + 57, $this->fit($note, 'regular', 7, $width - 14), 'regular', 7, self::MUTED);
            }
        }
        $this->y += 74;
    }

    /** @param list<array{0: string, 1: float}> $series date, clicks */
    private function chart(string $title, array $series): void
    {
        if ($series === []) {
            return;
        }
        $height = 96.0;
        $this->ensure($height + 40);
        $this->pdf->text($this->page, self::MARGIN, $this->y + 10, $title, 'bold', 10, self::TEXT);
        $this->y += 18;
        $max = max(1.0, ...array_map(static fn(array $p): float => $p[1], $series));
        $axis = 34.0;
        $left = self::MARGIN + $axis;
        $width = self::CONTENT - $axis;
        foreach ([1.0, 0.5, 0.0] as $fraction) {
            $y = $this->y + $height * (1 - $fraction);
            $this->pdf->line($this->page, $left, $y, $left + $width, $y, self::BORDER);
            $label = number_format($max * $fraction);
            $this->pdf->text($this->page, $left - 6 - $this->pdf->width($label, 'regular', 7), $y + 2.5, $label, 'regular', 7, self::MUTED);
        }
        $slot = $width / count($series);
        $bar = max(0.8, $slot * 0.7);
        foreach ($series as $i => [$date, $clicks]) {
            $h = $height * $clicks / $max;
            if ($h > 0) {
                $this->pdf->rect($this->page, $left + $i * $slot + ($slot - $bar) / 2, $this->y + $height - $h, $bar, $h, $this->accent);
            }
        }
        $first = $series[0][0];
        $last = $series[count($series) - 1][0];
        $this->pdf->text($this->page, $left, $this->y + $height + 11, $first, 'regular', 7, self::MUTED);
        $this->pdf->text($this->page, $left + $width - $this->pdf->width($last, 'regular', 7), $this->y + $height + 11, $last, 'regular', 7, self::MUTED);
        $this->y += $height + 24;
    }

    /**
     * A table with an optional title kept on the same page as its first rows.
     *
     * @param list<array{0: string, 1: float, 2: string}> $columns title, width, alignment
     * @param array<array<int, string>> $rows
     */
    private function table(?string $title, array $columns, array $rows): void
    {
        $rowHeight = 17.0;
        $header = function () use ($columns, $rowHeight): void {
            $this->pdf->rect($this->page, self::MARGIN, $this->y, self::CONTENT, $rowHeight, self::SHADE);
            $this->cells($columns, array_column($columns, 0), 'bold', self::MUTED);
            $this->y += $rowHeight;
        };
        // Short tables stay on one page; long ones start with at least two rows.
        $titleHeight = $title !== null ? 16.0 : 0.0;
        $whole = $titleHeight + $rowHeight * (count($rows) + 1);
        $this->ensure($whole <= 380 ? $whole : $titleHeight + $rowHeight * 3);
        if ($title !== null) {
            $this->pdf->text($this->page, self::MARGIN, $this->y + 10, $title, 'bold', 10.5, self::TEXT);
            $this->y += $titleHeight;
        }
        $header();
        foreach ($rows as $row) {
            if ($this->y + $rowHeight > self::BOTTOM) {
                $this->newPage();
                $header();
            }
            $this->cells($columns, $row, 'regular', self::TEXT);
            $this->y += $rowHeight;
            $this->pdf->line($this->page, self::MARGIN, $this->y, self::MARGIN + self::CONTENT, $this->y, self::BORDER);
        }
        $this->y += 12;
    }

    /**
     * @param list<array{0: string, 1: float, 2: string}> $columns
     * @param array<int, string> $values
     */
    private function cells(array $columns, array $values, string $font, string $color): void
    {
        $x = self::MARGIN;
        foreach ($columns as $i => [, $width, $align]) {
            $text = $this->fit($values[$i] ?? '', $font, 8.5, $width - 12);
            $tx = $align === 'right' ? $x + $width - 6 - $this->pdf->width($text, $font, 8.5) : $x + 6;
            $this->pdf->text($this->page, $tx, $this->y + 11.5, $text, $font, 8.5, $color);
            $x += $width;
        }
    }

    private function bullet(string $title, string $detail, bool $wrapDetail = true): void
    {
        $this->ensure(30);
        $this->pdf->rect($this->page, self::MARGIN + 2, $this->y + 5, 3, 3, $this->accent);
        $indent = self::MARGIN + 12;
        foreach ($this->wrap($title, 'bold', 9.5, self::CONTENT - 12) as $line) {
            $this->ensure(14);
            $this->pdf->text($this->page, $indent, $this->y + 9.5, $line, 'bold', 9.5, self::TEXT);
            $this->y += 13;
        }
        $lines = $wrapDetail ? $this->wrap($detail, 'regular', 8.5, self::CONTENT - 12) : [$this->fit($detail, 'regular', 8.5, self::CONTENT - 12)];
        foreach ($lines as $line) {
            $this->ensure(12);
            $this->pdf->text($this->page, $indent, $this->y + 8.5, $line, 'regular', 8.5, self::MUTED);
            $this->y += 11.5;
        }
        $this->y += 4;
    }

    private function heading(string $title): void
    {
        $this->ensure(110);
        $this->y += 8;
        $this->pdf->rect($this->page, self::MARGIN, $this->y + 1, 3, 14, $this->accent);
        $this->pdf->text($this->page, self::MARGIN + 10, $this->y + 12.5, $title, 'bold', 13, self::TEXT);
        $this->y += 24;
    }

    private function subheading(string $title): void
    {
        $this->ensure(70);
        $this->pdf->text($this->page, self::MARGIN, $this->y + 10, $title, 'bold', 10.5, self::TEXT);
        $this->y += 16;
    }

    private function paragraph(string $text, string $font, float $size, string $color, ?float $lineHeight = null): void
    {
        $lineHeight ??= $size * 1.4;
        foreach ($this->wrap($text, $font, $size, self::CONTENT) as $line) {
            $this->ensure($lineHeight);
            $this->pdf->text($this->page, self::MARGIN, $this->y + $size, $line, $font, $size, $color);
            $this->y += $lineHeight;
        }
    }

    /** @return list<string> */
    private function wrap(string $text, string $font, float $size, float $width): array
    {
        $lines = [];
        $current = '';
        foreach (preg_split('/\s+/u', trim($text)) ?: [] as $word) {
            $candidate = $current === '' ? $word : $current . ' ' . $word;
            if ($this->pdf->width($candidate, $font, $size) <= $width) {
                $current = $candidate;
                continue;
            }
            if ($current !== '') {
                $lines[] = $current;
            }
            while ($this->pdf->width($word, $font, $size) > $width && mb_strlen($word) > 1) {
                $cut = mb_strlen($word);
                while ($cut > 1 && $this->pdf->width(mb_substr($word, 0, $cut), $font, $size) > $width) {
                    --$cut;
                }
                $lines[] = mb_substr($word, 0, $cut);
                $word = mb_substr($word, $cut);
            }
            $current = $word;
        }
        if ($current !== '') {
            $lines[] = $current;
        }

        return $lines;
    }

    /** One line, shortened with an ellipsis to the width. */
    private function fit(string $text, string $font, float $size, float $width): string
    {
        $text = trim((string) preg_replace('/\s+/u', ' ', $text));
        if ($this->pdf->width($text, $font, $size) <= $width) {
            return $text;
        }
        $length = mb_strlen($text);
        while ($length > 0 && $this->pdf->width(mb_substr($text, 0, $length) . '…', $font, $size) > $width) {
            --$length;
        }

        return mb_substr($text, 0, $length) . '…';
    }

    private function ensure(float $height): void
    {
        if ($this->y + $height > self::BOTTOM) {
            $this->newPage();
        }
    }

    private function newPage(): void
    {
        $this->page = $this->pdf->addPage();
        $this->y = self::MARGIN;
    }

    /** @return array{0: string, 1: string} */
    private static function percentChange(int $now, int $before): array
    {
        return $before > 0 ? self::change(($now - $before) / $before * 100, '%+.1f %%', false) : ['no earlier data', self::MUTED];
    }

    /** @return array{0: string, 1: string} change text with an arrow for its direction and a colour for whether it is an improvement */
    private static function change(float $diff, string $format, bool $lowerIsBetter): array
    {
        if (abs($diff) < 0.05) {
            return ['no change', self::MUTED];
        }
        $good = $lowerIsBetter ? $diff < 0 : $diff > 0;

        return [($diff > 0 ? '↑ ' : '↓ ') . sprintf($format, $diff), $good ? self::GOOD : self::BAD];
    }
}
