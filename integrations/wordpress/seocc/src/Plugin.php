<?php

declare(strict_types=1);

namespace SccIndexNow;

final class Plugin
{
    public const OPTION = 'scc_indexnow_settings';
    public const HOOK = 'scc_indexnow_submit';
    public const RESULT = 'scc_indexnow_last_result';

    public function register(): void
    {
        add_action('admin_menu', [$this, 'menu']);
        add_action('admin_init', [$this, 'settings']);
        add_action('parse_request', [$this, 'serveKey'], 0);
        add_action('wp_after_insert_post', [$this, 'saved'], 10, 4);
        add_action('before_delete_post', [$this, 'deleted'], 10, 2);
        add_action(self::HOOK, [$this, 'submit'], 10, 3);
    }

    public function menu(): void
    {
        add_options_page('SEOcc', 'SEOcc', 'manage_options', 'seocc', [$this, 'page']);
    }

    public function settings(): void
    {
        register_setting('scc_indexnow', self::OPTION, ['type' => 'array', 'sanitize_callback' => [$this, 'sanitize'], 'show_in_rest' => false]);
    }

    /** @return array{key: string, enabled: bool} */
    public function sanitize(mixed $input): array
    {
        $old = $this->configuration();
        if (!current_user_can('manage_options')) {
            return $old;
        }
        $input = is_array($input) ? $input : [];
        $raw = is_string($input['key'] ?? null) ? trim($input['key']) : '';
        $key = Policy::key($raw);
        if ($raw !== '' && $key === '') {
            add_settings_error(self::OPTION, 'key', 'Paste the 32-character lowercase key generated by SEOcc. Existing settings were retained.');
            return $old;
        }
        $enabled = in_array($input['enabled'] ?? null, ['1', true], true) && $key !== '';
        if ($enabled && !$this->eligibleSite()) {
            add_settings_error(self::OPTION, 'site', 'Automatic submissions require a public HTTPS website.');
            $enabled = false;
        }
        if ($key !== $old['key'] || !$enabled) {
            wp_unschedule_hook(self::HOOK);
            delete_option(self::RESULT);
        }
        return ['key' => $key, 'enabled' => $enabled];
    }

    /** @return array{key: string, enabled: bool} */
    private function configuration(): array
    {
        $value = get_option(self::OPTION, []);
        return ['key' => Policy::key(is_array($value) && is_string($value['key'] ?? null) ? $value['key'] : ''),
            'enabled' => is_array($value) && ($value['enabled'] ?? null) === true];
    }

    private function eligibleSite(): bool
    {
        return Policy::host(home_url('/')) !== null && (string) get_option('blog_public') === '1' && $this->activeSite();
    }

    /** In a network, archived, spam and deleted sites never serve the key or notify. */
    private function activeSite(): bool
    {
        if (!is_multisite()) {
            return true;
        }
        $site = get_site();
        return $site instanceof \WP_Site && $site->archived === '0' && $site->spam === '0' && $site->deleted === '0';
    }

    /**
     * Runs $callback on this site, or on every site of the current network
     * in batches; settings and scheduled events are stored per site.
     *
     * @param callable(): void $callback
     */
    public static function eachSite(callable $callback, bool $network): void
    {
        if (!$network || !is_multisite()) {
            $callback();
            return;
        }
        $offset = 0;
        do {
            $batch = get_sites(['fields' => 'ids', 'number' => 100, 'offset' => $offset, 'network_id' => get_current_network_id()]);
            $ids = is_array($batch) ? array_values(array_filter($batch, 'is_int')) : [];
            foreach ($ids as $id) {
                switch_to_blog($id);
                try {
                    $callback();
                } finally {
                    restore_current_blog();
                }
            }
            $offset += 100;
        } while (count($ids) === 100);
    }

    public function serveKey(): void
    {
        $key = $this->configuration()['key'];
        $method = is_string($_SERVER['REQUEST_METHOD'] ?? null) ? $_SERVER['REQUEST_METHOD'] : '';
        $uri = is_string($_SERVER['REQUEST_URI'] ?? null) ? $_SERVER['REQUEST_URI'] : '';
        if (Policy::host(home_url('/')) === null || !$this->activeSite() || !Policy::keyRequest($method, $uri, $key, Policy::basePath(home_url('/')))) {
            return;
        }
        status_header(200);
        nocache_headers();
        header('Content-Type: text/plain; charset=utf-8');
        header('X-Content-Type-Options: nosniff');
        if ($method === 'GET') {
            echo $key;
        }
        exit;
    }

    public function saved(int $id, \WP_Post $post, bool $update, ?\WP_Post $before): void
    {
        if (wp_is_post_revision($id) || wp_is_post_autosave($id)) {
            return;
        }
        if ($this->publicPost($post)) {
            $this->queue(get_permalink($post));
        }
        if ($before !== null && $this->publicPost($before)) {
            $this->queue(get_permalink($before));
        }
    }

    public function deleted(int $id, \WP_Post $post): void
    {
        if ($this->publicPost($post)) {
            $this->queue(get_permalink($post));
        }
    }

    private function publicPost(\WP_Post $post): bool
    {
        return $post->post_status === 'publish' && $post->post_type !== 'attachment'
            && $post->post_password === '' && is_post_publicly_viewable($post);
    }

    private function queue(string|false $url): void
    {
        $settings = $this->configuration();
        if (!$settings['enabled'] || $settings['key'] === '' || !$this->eligibleSite() || !is_string($url) || !Policy::url($url, home_url('/'))) {
            return;
        }
        $this->schedule($url, $settings['key'], 0, 60);
    }

    private function schedule(string $url, string $key, int $attempt, int $delay): bool
    {
        $args = [$url, $key, $attempt];
        if (wp_next_scheduled(self::HOOK, $args) !== false) {
            return true;
        }
        $result = wp_schedule_single_event(time() + $delay, self::HOOK, $args, true);
        if (is_wp_error($result) || $result === false) {
            $this->record(0, 'Could not schedule a notification. Check WordPress cron.', $attempt);
            return false;
        }
        return true;
    }

    public function submit(string $url, string $key, int $attempt): void
    {
        $settings = $this->configuration();
        if ($attempt < 0 || $attempt > 3 || !$settings['enabled'] || $settings['key'] !== $key || !$this->eligibleSite() || !Policy::url($url, home_url('/'))) {
            return;
        }
        $response = wp_safe_remote_post(Policy::ENDPOINT, [
            'timeout' => 10, 'redirection' => 0, 'sslverify' => true, 'limit_response_size' => 1024,
            'headers' => ['Content-Type' => 'application/json; charset=utf-8'],
            'body' => wp_json_encode(Policy::payload($url, home_url('/'), $key)),
        ]);
        $status = is_wp_error($response) ? 0 : (int) wp_remote_retrieve_response_code($response);
        $delay = Policy::retryDelay($status, $attempt);
        $message = match ($status) {
            200 => 'Accepted by IndexNow; indexing is not guaranteed.',
            202 => 'Accepted; IndexNow is validating the key file.',
            403, 422 => 'Rejected. Check the public key file and exact website host.',
            400 => 'Rejected as an invalid request.',
            0 => 'IndexNow could not be reached.',
            default => 'IndexNow returned HTTP ' . $status . '.',
        };
        if ($delay !== null) {
            $retryAfter = is_wp_error($response) ? '' : wp_remote_retrieve_header($response, 'retry-after');
            if (is_string($retryAfter) && ctype_digit($retryAfter)) {
                $delay = max($delay, min(86400, (int) $retryAfter));
            }
            $message .= $this->schedule($url, $key, $attempt + 1, $delay)
                ? ' A retry is scheduled.' : ' Could not schedule a retry. Check WordPress cron.';
        } elseif ($status === 0 || $status === 429 || $status >= 500) {
            $message .= ' Retry limit reached; update the public post to try again.';
        }
        $this->record($status, $message, $attempt);
    }

    private function record(int $status, string $message, int $attempt): void
    {
        update_option(self::RESULT, ['time' => gmdate('Y-m-d H:i:s'), 'status' => $status, 'message' => $message, 'attempt' => $attempt + 1], false);
    }

    public function deactivate(bool $networkWide = false): void
    {
        $basename = plugin_basename(dirname(__DIR__) . '/seocc.php');
        self::eachSite(static function () use ($networkWide, $basename): void {
            // After a network deactivation, sites that activated SEOcc themselves keep their queue.
            if (!$networkWide || !in_array($basename, (array) get_option('active_plugins', []), true)) {
                wp_unschedule_hook(self::HOOK);
            }
        }, $networkWide);
    }

    public function page(): void
    {
        if (!current_user_can('manage_options')) {
            return;
        }
        $settings = $this->configuration();
        $result = get_option(self::RESULT, []);
        echo '<div class="wrap"><h1>SEOcc</h1>';
        echo '<p>In SEOcc, open project Settings → IndexNow, generate a key and paste it here. This public key is not a license key or an SEOcc login token.</p>';
        settings_errors(self::OPTION);
        echo '<form action="options.php" method="post">';
        settings_fields('scc_indexnow');
        echo '<p><label for="scc-key">SEOcc key</label><br><input id="scc-key" name="' . esc_attr(self::OPTION) . '[key]" type="text" class="regular-text" maxlength="32" value="' . esc_attr($settings['key']) . '" autocomplete="off"></p>';
        echo '<p><label><input type="checkbox" name="' . esc_attr(self::OPTION) . '[enabled]" value="1" ' . checked($settings['enabled'], true, false) . '> Notify IndexNow when public posts, pages or public custom post types change</label></p>';
        submit_button();
        echo '</form>';
        if ($settings['key'] !== '' && Policy::host(home_url('/')) !== null) {
            $location = home_url('/' . $settings['key'] . '.txt');
            echo '<p>Public key file: <a href="' . esc_url($location) . '">' . esc_html($location) . '</a>. Save, open this link, and then use SEOcc’s Check key file button.</p>';
        }
        if (!$this->eligibleSite()) {
            echo '<p>Automatic submissions require a public HTTPS site that search engines may index, with a plain home address (no port or query).</p>';
        } elseif (Policy::basePath(home_url('/')) !== '/') {
            echo '<p>This site’s home address is in a subdirectory, so the key file and notifications are limited to addresses under ' . esc_html(Policy::basePath(home_url('/'))) . '. In SEOcc, enter ' . esc_html(Policy::basePath(home_url('/'))) . ' as the Site path when you choose Check key file.</p>';
        }
        if (is_multisite()) {
            echo '<p>These settings apply to this site only. In a WordPress network each site keeps its own key, opt-in and last result, so set up every site you want SEOcc to notify.</p>';
        }
        echo '<p>Notifications run through WP-Cron with at most three retries. Low-traffic sites should configure a real cron runner. Activating this plugin does not submit existing content. Avoid enabling another IndexNow plugin alongside this one.</p>';
        echo '<p>Only changed page URLs, the website host and public key are sent to api.indexnow.org. No content, SEOcc credentials or personal user data is sent. Plugin submissions appear here, not in SEOcc’s submission history.</p>';
        if (is_array($result) && is_string($result['message'] ?? null) && is_string($result['time'] ?? null)) {
            echo '<h2>Last notification</h2><p>' . esc_html($result['time'] . ' UTC · ' . $result['message']) . '</p>';
        }
        echo '</div>';
    }
}
